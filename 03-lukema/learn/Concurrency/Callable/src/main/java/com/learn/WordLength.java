package com.learn;


public class WordLength
{
   private String word;

   private int    length;

   public void setWord(String word)
   {
      this.word = word;
   }

   public String getWord()
   {
      return word;
   }

   public void setLength(int length)
   {
      this.length = length;
   }

   public int getLength()
   {
      return length;
   }
}
