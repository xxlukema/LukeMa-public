package com.learn.core.momentum;


public class MomentumData
{
   private float mf         = 0;

   private float tr         = 0;

   private float averageX   = 0;

   private float highTBP    = 0;

   private float lowTBP     = 0;

   private float highStop   = 0;

   private float lowStop    = 0;

   private float highTarget = 0;

   private float lowTarget  = 0;

   public float getMf()
   {
      return mf;
   }

   public void setMf(float mf)
   {
      this.mf = mf;
   }

   public float getTr()
   {
      return tr;
   }

   public void setTr(float tr)
   {
      this.tr = tr;
   }

   public float getAverageX()
   {
      return averageX;
   }

   public void setAverageX(float averageX)
   {
      this.averageX = averageX;
   }

   public float getHighTBP()
   {
      return highTBP;
   }

   public void setHighTBP(float highTBP)
   {
      this.highTBP = highTBP;
   }

   public float getLowTBP()
   {
      return lowTBP;
   }

   public void setLowTBP(float lowTBP)
   {
      this.lowTBP = lowTBP;
   }

   public float getHighStop()
   {
      return highStop;
   }

   public void setHighStop(float highStop)
   {
      this.highStop = highStop;
   }

   public float getLowStop()
   {
      return lowStop;
   }

   public void setLowStop(float lowStop)
   {
      this.lowStop = lowStop;
   }

   public float getHighTarget()
   {
      return highTarget;
   }

   public void setHighTarget(float highTarget)
   {
      this.highTarget = highTarget;
   }

   public float getLowTarget()
   {
      return lowTarget;
   }

   public void setLowTarget(float lowTarget)
   {
      this.lowTarget = lowTarget;
   }

}
